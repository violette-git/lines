#!/usr/bin/env node
// Copies the app's pure AI prompt module and the domain types it needs into the Edge Function
// folder, rewriting imports for Deno. Run after any change to src/ai/prompt.ts or src/domain:
//
//   node supabase/scripts/sync-prompt.mjs          (write files)
//   node supabase/scripts/sync-prompt.mjs --check  (exit 1 if the copies are out of date)
//
// Why: Edge Functions are deployed from supabase/functions only and cannot import from src/, but
// "proxy" mode must send Claude exactly the same prompt and tool schema as "direct" mode.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const shared = join(root, 'supabase', 'functions', '_shared');
const check = process.argv.includes('--check');

const HEADER = (src) =>
  `// GENERATED by supabase/scripts/sync-prompt.mjs from ${src}. Do not edit by hand:\n` +
  `// change the source file and re-run the script.\n`;

const jobs = [
  { src: 'src/domain/types.ts', dest: 'domain/types.ts', rewrite: relTs },
  { src: 'src/domain/nodeSchemas.ts', dest: 'domain/nodeSchemas.ts', rewrite: relTs },
  { src: 'src/domain/contracts.ts', dest: 'domain/contracts.ts', rewrite: relTs },
  { src: 'src/ai/prompt.ts', dest: 'prompt.ts', rewrite: aliasToShared },
];

/** './x' -> './x.ts' (Deno needs explicit extensions). */
function relTs(code) {
  return code.replace(/from '\.\/([\w-]+)'/g, "from './$1.ts'");
}

/** '@/domain/x' -> './domain/x.ts'. */
function aliasToShared(code) {
  return code.replace(/from '@\/domain\/([\w-]+)'/g, "from './domain/$1.ts'");
}

let stale = false;
for (const job of jobs) {
  const srcPath = join(root, job.src);
  if (!existsSync(srcPath)) {
    console.error(`missing source ${job.src}`);
    process.exit(2);
  }
  const out = HEADER(job.src) + job.rewrite(readFileSync(srcPath, 'utf8'));
  const bad = [...out.matchAll(/from '([^']+)'/g)].map((m) => m[1]).filter((s) => !/^\.\/[\w/-]+\.ts$/.test(s));
  if (bad.length) {
    console.error(`${job.src}: imports that cannot run in Deno after rewrite: ${bad.join(', ')}`);
    process.exit(2);
  }
  if (out.includes(String.fromCharCode(0x2014))) {
    console.error(`${job.src}: contains an em-dash character`);
    process.exit(2);
  }
  const destPath = join(shared, job.dest);
  const current = existsSync(destPath) ? readFileSync(destPath, 'utf8') : '';
  if (current === out) continue;
  stale = true;
  if (check) {
    console.error(`out of date: supabase/functions/_shared/${job.dest}`);
  } else {
    mkdirSync(dirname(destPath), { recursive: true });
    writeFileSync(destPath, out);
    console.log(`wrote supabase/functions/_shared/${job.dest}`);
  }
}
if (check && stale) process.exit(1);
if (!stale) console.log('already in sync');
